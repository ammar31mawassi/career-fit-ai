create extension if not exists pgmq;

do $$
begin
  if not exists (
    select 1 from pgmq.list_queues() where queue_name = 'careerfit_job_recommendations'
  ) then
    perform pgmq.create('careerfit_job_recommendations');
  end if;
end
$$;

create table if not exists public.shared_job_catalog (
  id bigint generated by default as identity primary key,
  content_hash text not null unique,
  source_url text not null default '',
  application_link text not null default '',
  company text not null default 'Unknown Company',
  role text not null default 'Unknown Role',
  location text not null default '',
  description_text text not null default '',
  requirements_json text not null default '{}',
  domain text not null default '',
  career_fields_json text not null default '[]',
  source_confidence double precision not null default 0,
  first_seen_by uuid references auth.users(id) on delete set null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.recommendation_runs (
  id bigint generated by default as identity primary key,
  catalog_job_id bigint not null references public.shared_job_catalog(id) on delete cascade,
  source_user_id uuid references auth.users(id) on delete set null,
  status text not null default 'running',
  candidate_count integer not null default 0,
  scored_count integer not null default 0,
  strong_count integer not null default 0,
  error text not null default '',
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.job_recommendations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  catalog_job_id bigint not null references public.shared_job_catalog(id) on delete cascade,
  score double precision not null default 0,
  fit_level text not null default 'Weak',
  confidence double precision not null default 0,
  career_fields_json text not null default '[]',
  reasons_json text not null default '[]',
  match_snapshot_json text not null default '{}',
  model_version text not null default '',
  status text not null default 'shadow_observation',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_job_recommendation_version unique (user_id, catalog_job_id, model_version)
);

create index if not exists profile_interests_interest_profile_idx
  on public.profile_interests (interest, profile_id);
create index if not exists shared_job_catalog_domain_updated_idx
  on public.shared_job_catalog (domain, updated_at desc) where active = true;
create index if not exists shared_job_catalog_first_seen_idx
  on public.shared_job_catalog (first_seen_by, created_at desc);
create index if not exists recommendation_runs_status_created_idx
  on public.recommendation_runs (status, created_at);
create index if not exists recommendation_runs_catalog_idx
  on public.recommendation_runs (catalog_job_id, created_at desc);
create index if not exists job_recommendations_user_status_score_idx
  on public.job_recommendations (user_id, status, score desc);
create index if not exists job_recommendations_catalog_idx
  on public.job_recommendations (catalog_job_id);

alter table public.shared_job_catalog enable row level security;
alter table public.recommendation_runs enable row level security;
alter table public.job_recommendations enable row level security;

drop policy if exists shared_job_catalog_client_deny on public.shared_job_catalog;
create policy shared_job_catalog_client_deny on public.shared_job_catalog
  for all to anon, authenticated using (false) with check (false);

drop policy if exists recommendation_runs_client_deny on public.recommendation_runs;
create policy recommendation_runs_client_deny on public.recommendation_runs
  for all to anon, authenticated using (false) with check (false);

drop policy if exists job_recommendations_owner_select on public.job_recommendations;
create policy job_recommendations_owner_select on public.job_recommendations
  for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists job_recommendations_owner_update on public.job_recommendations;
create policy job_recommendations_owner_update on public.job_recommendations
  for update to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
