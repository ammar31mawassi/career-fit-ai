-- Independent Goozali discovery beta and consented notification delivery.

create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net with schema extensions;

alter table public.shared_job_catalog
  add column if not exists source_name text not null default 'community',
  add column if not exists external_id text not null default '',
  add column if not exists source_published_at timestamptz,
  add column if not exists last_seen_at timestamptz;

create unique index if not exists shared_job_catalog_source_external_uq
  on public.shared_job_catalog (source_name, external_id)
  where external_id <> '';
create index if not exists shared_job_catalog_source_seen_idx
  on public.shared_job_catalog (source_name, last_seen_at desc);

create table if not exists public.job_source_runs (
  id bigint generated by default as identity primary key,
  source_name text not null,
  status text not null default 'running',
  records_seen integer not null default 0,
  records_valid integer not null default 0,
  created_count integer not null default 0,
  updated_count integer not null default 0,
  ignored_count integer not null default 0,
  deactivated_count integer not null default 0,
  error_code text not null default '',
  error text not null default '',
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  constraint job_source_runs_status_check check (status in ('running', 'completed', 'failed', 'disabled'))
);

create table if not exists public.job_discovery_beta_members (
  user_id uuid primary key references auth.users(id) on delete cascade,
  market_code text not null default 'IL',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.job_notification_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email_enabled boolean not null default false,
  unsubscribed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.notification_deliveries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  recommendation_id bigint not null references public.job_recommendations(id) on delete cascade,
  channel text not null default 'email',
  status text not null default 'queued',
  attempts integer not null default 0,
  provider_message_id text not null default '',
  error_code text not null default '',
  error text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  sent_at timestamptz,
  constraint uq_notification_delivery_channel unique (recommendation_id, channel),
  constraint notification_deliveries_status_check check (status in ('queued', 'sending', 'sent', 'failed', 'suppressed'))
);

create index if not exists job_source_runs_source_created_idx
  on public.job_source_runs (source_name, created_at desc);
create index if not exists job_discovery_beta_market_active_idx
  on public.job_discovery_beta_members (market_code, active);
create index if not exists job_notification_preferences_email_idx
  on public.job_notification_preferences (email_enabled, updated_at desc)
  where email_enabled = true;
create index if not exists notification_deliveries_queue_idx
  on public.notification_deliveries (status, created_at)
  where status in ('queued', 'failed');
create index if not exists notification_deliveries_user_created_idx
  on public.notification_deliveries (user_id, created_at desc);

alter table public.job_source_runs enable row level security;
alter table public.job_discovery_beta_members enable row level security;
alter table public.job_notification_preferences enable row level security;
alter table public.notification_deliveries enable row level security;

drop policy if exists job_source_runs_client_deny on public.job_source_runs;
create policy job_source_runs_client_deny on public.job_source_runs
  for all to anon, authenticated using (false) with check (false);

drop policy if exists job_discovery_beta_owner_select on public.job_discovery_beta_members;
create policy job_discovery_beta_owner_select on public.job_discovery_beta_members
  for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists job_notification_preferences_owner_select on public.job_notification_preferences;
create policy job_notification_preferences_owner_select on public.job_notification_preferences
  for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists job_notification_preferences_owner_update on public.job_notification_preferences;
create policy job_notification_preferences_owner_update on public.job_notification_preferences
  for update to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists notification_deliveries_client_deny on public.notification_deliveries;
create policy notification_deliveries_client_deny on public.notification_deliveries
  for all to anon, authenticated using (false) with check (false);

create extension if not exists pgmq;
do $$
begin
  if not exists (
    select 1 from pgmq.list_queues() where queue_name = 'careerfit_email_notifications'
  ) then
    perform pgmq.create('careerfit_email_notifications');
  end if;
end
$$;
