-- Privacy-safe recommendation feedback and conservative field calibration.

alter table public.job_recommendations
  add column if not exists materialized_job_id bigint
  references public.jobs(id) on delete set null;

create index if not exists job_recommendations_materialized_job_idx
  on public.job_recommendations (materialized_job_id)
  where materialized_job_id is not null;

create table if not exists public.recommendation_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  recommendation_id bigint not null references public.job_recommendations(id) on delete cascade,
  catalog_job_id bigint not null references public.shared_job_catalog(id) on delete cascade,
  materialized_job_id bigint references public.jobs(id) on delete set null,
  event_type text not null,
  dismiss_reason text not null default '',
  score double precision not null default 0,
  score_band text not null,
  career_field text not null default 'unknown',
  source_name text not null default 'community',
  model_version text not null default '',
  created_at timestamptz not null default now(),
  constraint uq_recommendation_event_type
    unique (user_id, recommendation_id, event_type),
  constraint recommendation_events_type_check
    check (event_type in ('viewed', 'saved', 'applied', 'dismissed')),
  constraint recommendation_events_band_check
    check (score_band in ('possible', 'medium', 'strong')),
  constraint recommendation_events_reason_check
    check (
      (
        event_type = 'dismissed'
        and dismiss_reason in (
          'too_senior',
          'wrong_field',
          'wrong_location',
          'missing_skills',
          'employment_type',
          'not_interested',
          'other'
        )
      )
      or (event_type <> 'dismissed' and dismiss_reason = '')
    )
);

create index if not exists recommendation_events_recommendation_idx
  on public.recommendation_events (recommendation_id);
create index if not exists recommendation_events_catalog_idx
  on public.recommendation_events (catalog_job_id);
create index if not exists recommendation_events_materialized_job_idx
  on public.recommendation_events (materialized_job_id)
  where materialized_job_id is not null;
create index if not exists recommendation_events_user_created_idx
  on public.recommendation_events (user_id, created_at desc);
create index if not exists recommendation_events_field_type_created_idx
  on public.recommendation_events (career_field, event_type, created_at desc);
create index if not exists recommendation_events_band_type_idx
  on public.recommendation_events (score_band, event_type);

create table if not exists public.recommendation_field_calibrations (
  career_field text primary key,
  minimum_score double precision not null default 40,
  sample_size integer not null default 0,
  positive_count integer not null default 0,
  negative_count integer not null default 0,
  possible_sample_size integer not null default 0,
  possible_positive_count integer not null default 0,
  medium_sample_size integer not null default 0,
  medium_positive_count integer not null default 0,
  window_days integer not null default 90,
  updated_at timestamptz not null default now(),
  constraint recommendation_field_threshold_check
    check (minimum_score in (40, 50, 65)),
  constraint recommendation_field_counts_check
    check (
      sample_size >= 0
      and positive_count >= 0
      and negative_count >= 0
      and positive_count + negative_count = sample_size
      and possible_sample_size >= 0
      and possible_positive_count between 0 and possible_sample_size
      and medium_sample_size >= 0
      and medium_positive_count between 0 and medium_sample_size
    )
);

alter table public.recommendation_events enable row level security;
alter table public.recommendation_field_calibrations enable row level security;

drop policy if exists recommendation_events_owner_select on public.recommendation_events;
create policy recommendation_events_owner_select on public.recommendation_events
  for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists recommendation_events_owner_insert on public.recommendation_events;

drop policy if exists recommendation_field_calibrations_client_deny
  on public.recommendation_field_calibrations;
create policy recommendation_field_calibrations_client_deny
  on public.recommendation_field_calibrations
  for all to anon, authenticated
  using (false)
  with check (false);
