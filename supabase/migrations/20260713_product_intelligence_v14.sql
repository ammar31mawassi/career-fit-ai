-- Durable scans, privacy-safe extraction telemetry, reviewed requirements,
-- correction-driven evaluation examples, and opt-in recommendations.

alter table public.profiles
  add column if not exists recommendations_enabled boolean not null default false;

create table if not exists public.job_requirement_revisions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  job_id bigint not null references public.jobs(id) on delete cascade,
  original_requirements_json text not null default '{}',
  corrected_requirements_json text not null default '{}',
  changed_fields_json text not null default '[]',
  matcher_version text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.job_scans (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  input_hash text not null default '',
  payload_json text not null default '{}',
  status text not null default 'queued',
  current_step text not null default 'queued',
  progress integer not null default 0 check (progress between 0 and 100),
  result_job_id bigint references public.jobs(id) on delete set null,
  trace_id text not null default '',
  attempts integer not null default 0,
  error_code text not null default '',
  error_message text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz,
  constraint job_scans_status_check check (
    status in ('queued', 'running', 'succeeded', 'failed', 'cancel_requested', 'cancelled')
  )
);

create table if not exists public.extraction_metrics (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  workflow_type text not null,
  subject_type text not null default '',
  subject_id bigint,
  strategy text not null default '',
  status text not null default 'succeeded',
  duration_ms integer not null default 0,
  input_length integer not null default 0,
  output_length integer not null default 0,
  fallback_reason text not null default '',
  counts_json text not null default '{}',
  error_code text not null default '',
  trace_id text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.evaluation_examples (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  example_type text not null,
  subject_id bigint,
  split text not null default 'train',
  label text not null,
  features_json text not null default '{}',
  model_version text not null default '',
  trace_id text not null default '',
  created_at timestamptz not null default now(),
  constraint evaluation_examples_split_check check (split in ('train', 'validation', 'test'))
);

create index if not exists profiles_recommendations_ready_idx
  on public.profiles (recommendations_enabled, status, updated_at desc)
  where recommendations_enabled = true and onboarding_completed = true;
create index if not exists job_requirement_revisions_job_created_idx
  on public.job_requirement_revisions (job_id, created_at desc);
create index if not exists job_scans_user_created_idx
  on public.job_scans (user_id, created_at desc);
create index if not exists job_scans_queue_idx
  on public.job_scans (status, created_at) where status in ('queued', 'cancel_requested');
create index if not exists extraction_metrics_workflow_created_idx
  on public.extraction_metrics (workflow_type, status, created_at desc);
create index if not exists extraction_metrics_trace_idx
  on public.extraction_metrics (trace_id) where trace_id <> '';
create index if not exists evaluation_examples_type_split_idx
  on public.evaluation_examples (example_type, split, created_at desc);

alter table public.job_requirement_revisions enable row level security;
alter table public.job_scans enable row level security;
alter table public.extraction_metrics enable row level security;
alter table public.evaluation_examples enable row level security;

drop policy if exists job_requirement_revisions_owner_all on public.job_requirement_revisions;
create policy job_requirement_revisions_owner_all on public.job_requirement_revisions
  for all to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists job_scans_owner_all on public.job_scans;
create policy job_scans_owner_all on public.job_scans
  for all to authenticated using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

-- Metrics and evaluation features are backend-only. Users receive their
-- correction history through the existing account export, not internal telemetry rows.
drop policy if exists extraction_metrics_client_deny on public.extraction_metrics;
create policy extraction_metrics_client_deny on public.extraction_metrics
  for all to anon, authenticated using (false) with check (false);

drop policy if exists evaluation_examples_client_deny on public.evaluation_examples;
create policy evaluation_examples_client_deny on public.evaluation_examples
  for all to anon, authenticated using (false) with check (false);

create extension if not exists pgmq;
do $$
begin
  if not exists (
    select 1 from pgmq.list_queues() where queue_name = 'careerfit_job_scans'
  ) then
    perform pgmq.create('careerfit_job_scans');
  end if;
end
$$;
